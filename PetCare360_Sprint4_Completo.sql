CREATE TABLE TB_USER (
    user_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    user_name     VARCHAR2(255) NOT NULL,
    email         VARCHAR2(255) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    enabled       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    CONSTRAINT TB_USER_PK PRIMARY KEY (user_id),
    CONSTRAINT TB_USER_EMAIL_UN UNIQUE (email),
    CONSTRAINT CK_TB_USER_ENABLED CHECK (enabled IN (0, 1))
);

CREATE TABLE TB_PET (
    pet_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    pet_name        VARCHAR2(255) NOT NULL,
    age             NUMBER(3) NOT NULL,
    weight          NUMBER(10,2) NOT NULL,
    breed           VARCHAR2(120) NOT NULL,
    species         VARCHAR2(40) DEFAULT 'DOG' NOT NULL,
    active          NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    tb_user_user_id NUMBER(10) NOT NULL,
    CONSTRAINT TB_PET_PK PRIMARY KEY (pet_id),
    CONSTRAINT TB_PET_TB_USER_FK FOREIGN KEY (tb_user_user_id)
        REFERENCES TB_USER (user_id),
    CONSTRAINT CK_TB_PET_AGE CHECK (age >= 0),
    CONSTRAINT CK_TB_PET_WEIGHT CHECK (weight > 0),
    CONSTRAINT CK_TB_PET_SPECIES CHECK (species IN ('DOG', 'CAT', 'OTHER')),
    CONSTRAINT CK_TB_PET_ACTIVE CHECK (active IN (0, 1))
);

CREATE TABLE TB_DEVICE (
    device_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    device_code    VARCHAR2(80) NOT NULL,
    device_status  CHAR(1) NOT NULL,
    device_battery NUMBER(3) NOT NULL,
    last_seen      TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    tb_pet_pet_id  NUMBER(10) NOT NULL,
    CONSTRAINT TB_DEVICE_PK PRIMARY KEY (device_id),
    CONSTRAINT TB_DEVICE_PET_UN UNIQUE (tb_pet_pet_id),
    CONSTRAINT TB_DEVICE_CODE_UN UNIQUE (device_code),
    CONSTRAINT TB_DEVICE_TB_PET_FK FOREIGN KEY (tb_pet_pet_id)
        REFERENCES TB_PET (pet_id),
    CONSTRAINT CK_TB_DEVICE_STATUS CHECK (device_status IN ('A', 'I', 'M')),
    CONSTRAINT CK_TB_DEVICE_BATTERY CHECK (device_battery BETWEEN 0 AND 100)
);

CREATE TABLE TB_SENSOR_DATA (
    sensor_id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    data_hora           TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    temperature         NUMBER(5,2) NOT NULL,
    heart_rate          NUMBER(3) NOT NULL,
    activity_level      VARCHAR2(20) NOT NULL,
    latitude            NUMBER(9,7) NOT NULL,
    longitude           NUMBER(10,7) NOT NULL,
    sensor_battery      NUMBER(3) NOT NULL,
    sensor_status       CHAR(1) NOT NULL,
    tb_device_device_id NUMBER(10) NOT NULL,
    CONSTRAINT TB_SENSOR_DATA_PK PRIMARY KEY (sensor_id),
    CONSTRAINT TB_SENSOR_DATA_DEVICE_FK FOREIGN KEY (tb_device_device_id)
        REFERENCES TB_DEVICE (device_id),
    CONSTRAINT CK_TB_SENSOR_TEMPERATURE CHECK (temperature BETWEEN 30 AND 45),
    CONSTRAINT CK_TB_SENSOR_HEART_RATE CHECK (heart_rate BETWEEN 40 AND 220),
    CONSTRAINT CK_TB_SENSOR_ACTIVITY CHECK (activity_level IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT CK_TB_SENSOR_STATUS CHECK (sensor_status IN ('A', 'I', 'M')),
    CONSTRAINT CK_TB_SENSOR_BATTERY CHECK (sensor_battery BETWEEN 0 AND 100)
);

CREATE TABLE TB_ALERT (
    alert_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    type          VARCHAR2(15) NOT NULL,
    message       VARCHAR2(255) NOT NULL,
    alert_level   VARCHAR2(10) NOT NULL,
    status        VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    created_at    TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    resolved_at   TIMESTAMP WITH LOCAL TIME ZONE,
    resolved_by   NUMBER(10),
    tb_pet_pet_id NUMBER(10) NOT NULL,
    CONSTRAINT TB_ALERT_PK PRIMARY KEY (alert_id),
    CONSTRAINT TB_ALERT_TB_PET_FK FOREIGN KEY (tb_pet_pet_id)
        REFERENCES TB_PET (pet_id),
    CONSTRAINT TB_ALERT_RESOLVED_BY_FK FOREIGN KEY (resolved_by)
        REFERENCES TB_USER (user_id),
    CONSTRAINT CK_TB_ALERT_TYPE CHECK (type IN ('ACTIVITY', 'TEMPERATURE', 'HEART_RATE', 'BATTERY')),
    CONSTRAINT CK_TB_ALERT_LEVEL CHECK (alert_level IN ('CRITICAL', 'INFO', 'WARNING')),
    CONSTRAINT CK_TB_ALERT_STATUS CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED'))
);

CREATE TABLE TB_AUTH (
    refresh_token   VARCHAR2(255) NOT NULL,
    expires_at      TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    tb_user_user_id NUMBER(10) NOT NULL,
    CONSTRAINT TB_AUTH_PK PRIMARY KEY (refresh_token),
    CONSTRAINT TB_AUTH_TB_USER_FK FOREIGN KEY (tb_user_user_id)
        REFERENCES TB_USER (user_id)
);

CREATE TABLE TB_LOG_ERRO (
    log_id        NUMBER(10) NOT NULL,
    objeto        VARCHAR2(100) NOT NULL,
    usuario       VARCHAR2(100) NOT NULL,
    data_erro     TIMESTAMP NOT NULL,
    codigo_erro   NUMBER,
    mensagem_erro VARCHAR2(4000),
    CONSTRAINT TB_LOG_ERRO_PK PRIMARY KEY (log_id)
);

CREATE TABLE TB_AUDITORIA_SENSOR (
    auditoria_id       NUMBER(10) NOT NULL,
    usuario_oracle     VARCHAR2(100) NOT NULL,
    tipo_operacao      VARCHAR2(10) NOT NULL,
    data_operacao      TIMESTAMP NOT NULL,
    valores_anteriores VARCHAR2(4000),
    valores_novos      VARCHAR2(4000),
    CONSTRAINT TB_AUDITORIA_SENSOR_PK PRIMARY KEY (auditoria_id),
    CONSTRAINT CK_TB_AUDITORIA_OPERACAO CHECK (tipo_operacao IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- Modulo clinico do Java: perfis, acompanhamento e comunicacao.
CREATE TABLE TB_ROLE (
    role_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(40) NOT NULL,
    description VARCHAR2(160),
    CONSTRAINT TB_ROLE_PK PRIMARY KEY (role_id),
    CONSTRAINT TB_ROLE_NAME_UN UNIQUE (name),
    CONSTRAINT CK_TB_ROLE_NAME CHECK (name IN ('ROLE_ADMIN', 'ROLE_CLIENTE', 'ROLE_VETERINARIO'))
);

CREATE TABLE TB_USER_ROLE (
    user_id NUMBER(10) NOT NULL,
    role_id NUMBER(10) NOT NULL,
    CONSTRAINT TB_USER_ROLE_PK PRIMARY KEY (user_id, role_id),
    CONSTRAINT TB_USER_ROLE_USER_FK FOREIGN KEY (user_id) REFERENCES TB_USER(user_id),
    CONSTRAINT TB_USER_ROLE_ROLE_FK FOREIGN KEY (role_id) REFERENCES TB_ROLE(role_id)
);

CREATE TABLE TB_PET_VETERINARIAN (
    pet_id NUMBER(10) NOT NULL,
    veterinarian_id NUMBER(10) NOT NULL,
    assigned_at TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT TB_PET_VETERINARIAN_PK PRIMARY KEY (pet_id, veterinarian_id),
    CONSTRAINT TB_PET_VET_PET_FK FOREIGN KEY (pet_id) REFERENCES TB_PET(pet_id),
    CONSTRAINT TB_PET_VET_USER_FK FOREIGN KEY (veterinarian_id) REFERENCES TB_USER(user_id),
    CONSTRAINT CK_TB_PET_VET_ACTIVE CHECK (active IN (0, 1))
);

CREATE TABLE TB_ALERT_HISTORY (
    history_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    alert_id NUMBER(10) NOT NULL,
    user_id NUMBER(10) NOT NULL,
    previous_status VARCHAR2(20),
    new_status VARCHAR2(20) NOT NULL,
    note VARCHAR2(255),
    created_at TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT TB_ALERT_HISTORY_PK PRIMARY KEY (history_id),
    CONSTRAINT TB_ALERT_HIST_ALERT_FK FOREIGN KEY (alert_id) REFERENCES TB_ALERT(alert_id),
    CONSTRAINT TB_ALERT_HIST_USER_FK FOREIGN KEY (user_id) REFERENCES TB_USER(user_id),
    CONSTRAINT CK_TB_ALERT_HIST_PREV CHECK (previous_status IS NULL OR previous_status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT CK_TB_ALERT_HIST_NEW CHECK (new_status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED'))
);

CREATE TABLE TB_PET_MESSAGE (
    message_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    pet_id NUMBER(10) NOT NULL,
    sender_id NUMBER(10) NOT NULL,
    receiver_id NUMBER(10) NOT NULL,
    subject VARCHAR2(120) NOT NULL,
    message VARCHAR2(1000) NOT NULL,
    status VARCHAR2(20) DEFAULT 'SENT' NOT NULL,
    created_at TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    read_at TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT TB_PET_MESSAGE_PK PRIMARY KEY (message_id),
    CONSTRAINT TB_PET_MSG_PET_FK FOREIGN KEY (pet_id) REFERENCES TB_PET(pet_id),
    CONSTRAINT TB_PET_MSG_SENDER_FK FOREIGN KEY (sender_id) REFERENCES TB_USER(user_id),
    CONSTRAINT TB_PET_MSG_RECEIVER_FK FOREIGN KEY (receiver_id) REFERENCES TB_USER(user_id),
    CONSTRAINT CK_TB_PET_MSG_STATUS CHECK (status IN ('SENT', 'READ', 'ANSWERED')),
    CONSTRAINT CK_TB_PET_MSG_USERS CHECK (sender_id <> receiver_id)
);

CREATE TABLE TB_APPOINTMENT (
    appointment_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    pet_id NUMBER(10) NOT NULL,
    tutor_id NUMBER(10) NOT NULL,
    veterinarian_id NUMBER(10) NOT NULL,
    scheduled_at TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    reason VARCHAR2(255) NOT NULL,
    status VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL,
    created_at TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT TB_APPOINTMENT_PK PRIMARY KEY (appointment_id),
    CONSTRAINT TB_APPT_PET_FK FOREIGN KEY (pet_id) REFERENCES TB_PET(pet_id),
    CONSTRAINT TB_APPT_TUTOR_FK FOREIGN KEY (tutor_id) REFERENCES TB_USER(user_id),
    CONSTRAINT TB_APPT_VET_FK FOREIGN KEY (veterinarian_id) REFERENCES TB_USER(user_id),
    CONSTRAINT CK_TB_APPT_STATUS CHECK (status IN ('REQUESTED', 'CONFIRMED', 'CANCELED', 'DONE')),
    CONSTRAINT CK_TB_APPT_USERS CHECK (tutor_id <> veterinarian_id)
);

CREATE TABLE TB_CARE_RECOMMENDATION (
    recommendation_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    pet_id NUMBER(10) NOT NULL,
    veterinarian_id NUMBER(10) NOT NULL,
    tutor_id NUMBER(10) NOT NULL,
    title VARCHAR2(120) NOT NULL,
    instructions VARCHAR2(1000) NOT NULL,
    priority VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at TIMESTAMP WITH LOCAL TIME ZONE,
    CONSTRAINT TB_CARE_REC_PK PRIMARY KEY (recommendation_id),
    CONSTRAINT TB_CARE_REC_PET_FK FOREIGN KEY (pet_id) REFERENCES TB_PET(pet_id),
    CONSTRAINT TB_CARE_REC_VET_FK FOREIGN KEY (veterinarian_id) REFERENCES TB_USER(user_id),
    CONSTRAINT TB_CARE_REC_TUTOR_FK FOREIGN KEY (tutor_id) REFERENCES TB_USER(user_id),
    CONSTRAINT CK_TB_CARE_REC_PRIORITY CHECK (priority IN ('LOW', 'NORMAL', 'HIGH')),
    CONSTRAINT CK_TB_CARE_REC_STATUS CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELED')),
    CONSTRAINT CK_TB_CARE_REC_USERS CHECK (tutor_id <> veterinarian_id)
);

CREATE INDEX IX_TB_PET_OWNER ON TB_PET(tb_user_user_id);
CREATE INDEX IX_TB_SENSOR_DEVICE_TIME ON TB_SENSOR_DATA(tb_device_device_id, data_hora);
CREATE INDEX IX_TB_ALERT_PET_STATUS ON TB_ALERT(tb_pet_pet_id, status);
CREATE INDEX IX_TB_USER_ROLE_ROLE ON TB_USER_ROLE(role_id);
CREATE INDEX IX_TB_PET_VET_USER ON TB_PET_VETERINARIAN(veterinarian_id);
CREATE INDEX IX_TB_ALERT_HIST_ALERT ON TB_ALERT_HISTORY(alert_id);
CREATE INDEX IX_TB_PET_MSG_RECEIVER ON TB_PET_MESSAGE(receiver_id);
CREATE INDEX IX_TB_APPT_VET_TIME ON TB_APPOINTMENT(veterinarian_id, scheduled_at);
CREATE INDEX IX_TB_CARE_REC_PET ON TB_CARE_RECOMMENDATION(pet_id);

CREATE SEQUENCE SQ_LOG_ERRO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SQ_AUDITORIA_SENSOR START WITH 1 INCREMENT BY 1 NOCACHE;

