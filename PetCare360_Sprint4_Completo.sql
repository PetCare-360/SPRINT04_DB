CREATE OR REPLACE PACKAGE BODY PKG_PETCARE360_CLINICO AS
    PROCEDURE PRC_LOG_FALHA(p_objeto IN VARCHAR2, p_codigo IN NUMBER, p_mensagem IN VARCHAR2) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO TB_LOG_ERRO(log_id, objeto, usuario, data_erro, codigo_erro, mensagem_erro)
        VALUES (SQ_LOG_ERRO.NEXTVAL, SUBSTR(p_objeto, 1, 100),
                SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSTIMESTAMP,
                p_codigo, SUBSTR(p_mensagem, 1, 4000));
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK; -- Preserva a excecao original caso o log falhe.
    END;

    FUNCTION FN_TEM_PERFIL(p_user_id IN NUMBER, p_role_name IN VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
        FROM TB_USER_ROLE ur JOIN TB_ROLE r ON r.role_id = ur.role_id
        JOIN TB_USER u ON u.user_id = ur.user_id
        WHERE ur.user_id = p_user_id AND r.name = p_role_name AND u.enabled = 1;
        RETURN v_count;
    END;

    PROCEDURE PRC_VALIDAR_ATENDIMENTO(p_pet_id IN NUMBER, p_tutor_id IN NUMBER,
                                        p_veterinario_id IN NUMBER) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM TB_PET
        WHERE pet_id = p_pet_id AND tb_user_user_id = p_tutor_id AND active = 1;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20710, 'Pet inexistente ou tutor sem acesso.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM TB_PET_VETERINARIAN
        WHERE pet_id = p_pet_id AND veterinarian_id = p_veterinario_id AND active = 1;
        IF v_count = 0 OR FN_TEM_PERFIL(p_veterinario_id, 'ROLE_VETERINARIO') = 0 THEN
            RAISE_APPLICATION_ERROR(-20711, 'Veterinario nao vinculado ao pet.');
        END IF;
    END;

    FUNCTION FN_TOTAL_CONSULTAS_PET(p_pet_id IN TB_PET.pet_id%TYPE) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM TB_PET WHERE pet_id = p_pet_id;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20701, 'Pet nao encontrado.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM TB_APPOINTMENT WHERE pet_id = p_pet_id;
        RETURN v_count;
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.FN_TOTAL_CONSULTAS_PET', SQLCODE, SQLERRM);
        RAISE;
    END;

    FUNCTION FN_VETERINARIO_VINCULADO(p_pet_id IN TB_PET.pet_id%TYPE,
        p_veterinario_id IN TB_USER.user_id%TYPE) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM TB_PET WHERE pet_id = p_pet_id;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20701, 'Pet nao encontrado.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM TB_PET_VETERINARIAN
        WHERE pet_id = p_pet_id AND veterinarian_id = p_veterinario_id AND active = 1;
        RETURN v_count;
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.FN_VETERINARIO_VINCULADO', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_ATRIBUIR_PERFIL(p_user_id IN TB_USER.user_id%TYPE,
        p_role_name IN TB_ROLE.name%TYPE) IS
        v_role_id TB_ROLE.role_id%TYPE;
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM TB_USER WHERE user_id = p_user_id AND enabled = 1;
        IF v_count = 0 THEN RAISE_APPLICATION_ERROR(-20702, 'Usuario ativo nao encontrado.'); END IF;
        BEGIN
            SELECT role_id INTO v_role_id FROM TB_ROLE WHERE name = p_role_name;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20703, 'Perfil nao encontrado.');
        END;
        SELECT COUNT(*) INTO v_count FROM TB_USER_ROLE
        WHERE user_id = p_user_id AND role_id = v_role_id;
        IF v_count > 0 THEN RAISE_APPLICATION_ERROR(-20704, 'Perfil ja atribuido.'); END IF;
        INSERT INTO TB_USER_ROLE(user_id, role_id) VALUES (p_user_id, v_role_id);
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.PRC_ATRIBUIR_PERFIL', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_VINCULAR_VETERINARIO(p_pet_id IN TB_PET.pet_id%TYPE,
        p_veterinario_id IN TB_USER.user_id%TYPE) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM TB_PET WHERE pet_id = p_pet_id AND active = 1;
        IF v_count = 0 THEN RAISE_APPLICATION_ERROR(-20701, 'Pet nao encontrado.'); END IF;
        IF FN_TEM_PERFIL(p_veterinario_id, 'ROLE_VETERINARIO') = 0 THEN
            RAISE_APPLICATION_ERROR(-20705, 'Usuario nao possui perfil veterinario.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM TB_PET_VETERINARIAN
        WHERE pet_id = p_pet_id AND veterinarian_id = p_veterinario_id;
        IF v_count > 0 THEN RAISE_APPLICATION_ERROR(-20706, 'Vinculo ja cadastrado.'); END IF;
        INSERT INTO TB_PET_VETERINARIAN(pet_id, veterinarian_id)
        VALUES (p_pet_id, p_veterinario_id);
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.PRC_VINCULAR_VETERINARIO', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_ENVIAR_MENSAGEM(p_pet_id IN TB_PET.pet_id%TYPE,
        p_sender_id IN TB_USER.user_id%TYPE, p_receiver_id IN TB_USER.user_id%TYPE,
        p_subject IN TB_PET_MESSAGE.subject%TYPE,
        p_message IN TB_PET_MESSAGE.message%TYPE) IS
        v_tutor_id TB_PET.tb_user_user_id%TYPE;
    BEGIN
        IF p_sender_id IS NULL OR p_receiver_id IS NULL OR
           p_sender_id = p_receiver_id OR TRIM(p_subject) IS NULL OR TRIM(p_message) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20707, 'Mensagem, assunto e destinatario devem ser validos.');
        END IF;
        BEGIN
            SELECT tb_user_user_id INTO v_tutor_id FROM TB_PET
            WHERE pet_id = p_pet_id AND active = 1;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20701, 'Pet nao encontrado.');
        END;
        IF NOT ((p_sender_id = v_tutor_id AND FN_VETERINARIO_VINCULADO(p_pet_id, p_receiver_id) = 1)
            OR (p_receiver_id = v_tutor_id AND FN_VETERINARIO_VINCULADO(p_pet_id, p_sender_id) = 1)) THEN
            RAISE_APPLICATION_ERROR(-20708, 'Mensagem permitida apenas entre tutor e veterinario vinculado.');
        END IF;
        INSERT INTO TB_PET_MESSAGE(pet_id, sender_id, receiver_id, subject, message)
        VALUES (p_pet_id, p_sender_id, p_receiver_id, p_subject, p_message);
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.PRC_ENVIAR_MENSAGEM', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_AGENDAR_CONSULTA(p_pet_id IN TB_PET.pet_id%TYPE,
        p_tutor_id IN TB_USER.user_id%TYPE, p_veterinario_id IN TB_USER.user_id%TYPE,
        p_scheduled_at IN TB_APPOINTMENT.scheduled_at%TYPE,
        p_reason IN TB_APPOINTMENT.reason%TYPE) IS
    BEGIN
        PRC_VALIDAR_ATENDIMENTO(p_pet_id, p_tutor_id, p_veterinario_id);
        IF p_scheduled_at IS NULL OR p_scheduled_at <= SYSTIMESTAMP OR TRIM(p_reason) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20712, 'Data futura e motivo sao obrigatorios.');
        END IF;
        INSERT INTO TB_APPOINTMENT(pet_id, tutor_id, veterinarian_id, scheduled_at, reason)
        VALUES (p_pet_id, p_tutor_id, p_veterinario_id, p_scheduled_at, p_reason);
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.PRC_AGENDAR_CONSULTA', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_CRIAR_RECOMENDACAO(p_pet_id IN TB_PET.pet_id%TYPE,
        p_tutor_id IN TB_USER.user_id%TYPE, p_veterinario_id IN TB_USER.user_id%TYPE,
        p_title IN TB_CARE_RECOMMENDATION.title%TYPE,
        p_instructions IN TB_CARE_RECOMMENDATION.instructions%TYPE,
        p_priority IN TB_CARE_RECOMMENDATION.priority%TYPE DEFAULT 'NORMAL') IS
    BEGIN
        PRC_VALIDAR_ATENDIMENTO(p_pet_id, p_tutor_id, p_veterinario_id);
        IF TRIM(p_title) IS NULL OR TRIM(p_instructions) IS NULL OR
           p_priority IS NULL OR p_priority NOT IN ('LOW', 'NORMAL', 'HIGH') THEN
            RAISE_APPLICATION_ERROR(-20713, 'Dados da recomendacao invalidos.');
        END IF;
        INSERT INTO TB_CARE_RECOMMENDATION
            (pet_id, veterinarian_id, tutor_id, title, instructions, priority)
        VALUES (p_pet_id, p_veterinario_id, p_tutor_id, p_title, p_instructions, p_priority);
    EXCEPTION WHEN OTHERS THEN
        PRC_LOG_FALHA('CLINICO.PRC_CRIAR_RECOMENDACAO', SQLCODE, SQLERRM);
        RAISE;
    END;

    PROCEDURE PRC_ATUALIZAR_ALERTA(p_alert_id IN TB_ALERT.alert_id%TYPE,
        p_user_id IN TB_USER.user_id%TYPE, p_new_status IN TB_ALERT.status%TYPE,
        p_note IN TB_ALERT_HISTORY.note%TYPE DEFAULT NULL) IS
        v_old_status TB_ALERT.status%TYPE;
        v_pet_id TB_PET.pet_id%TYPE;
        v_tutor_id TB_USER.user_id%TYPE;
        v_erro_codigo NUMBER;
        v_erro_mensagem VARCHAR2(4000);
    BEGIN
        SAVEPOINT SP_ATUALIZAR_ALERTA;
        BEGIN
            SELECT a.status, a.tb_pet_pet_id, p.tb_user_user_id
            INTO v_old_status, v_pet_id, v_tutor_id
            FROM TB_ALERT a JOIN TB_PET p ON p.pet_id = a.tb_pet_pet_id
            WHERE a.alert_id = p_alert_id FOR UPDATE OF a.status;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20714, 'Alerta nao encontrado.');
        END;
        IF p_user_id IS NULL OR
           (p_user_id <> v_tutor_id AND FN_VETERINARIO_VINCULADO(v_pet_id, p_user_id) = 0) THEN
            RAISE_APPLICATION_ERROR(-20715, 'Usuario sem acesso ao alerta.');
        END IF;
        IF p_new_status IS NULL OR NOT ((v_old_status = 'OPEN' AND p_new_status = 'IN_PROGRESS') OR
                (v_old_status = 'IN_PROGRESS' AND p_new_status = 'RESOLVED')) THEN
            RAISE_APPLICATION_ERROR(-20716, 'Transicao de status invalida.');
        END IF;
        UPDATE TB_ALERT
        SET status = p_new_status,
            resolved_at = CASE WHEN p_new_status = 'RESOLVED' THEN SYSTIMESTAMP ELSE NULL END,
            resolved_by = CASE WHEN p_new_status = 'RESOLVED' THEN p_user_id ELSE NULL END
        WHERE alert_id = p_alert_id;
        INSERT INTO TB_ALERT_HISTORY(alert_id, user_id, previous_status, new_status, note)
        VALUES (p_alert_id, p_user_id, v_old_status, p_new_status, p_note);
    EXCEPTION WHEN OTHERS THEN
        v_erro_codigo := SQLCODE;
        v_erro_mensagem := SQLERRM;
        ROLLBACK TO SP_ATUALIZAR_ALERTA;
        PRC_LOG_FALHA('CLINICO.PRC_ATUALIZAR_ALERTA', v_erro_codigo, v_erro_mensagem);
        RAISE;
    END;
END PKG_PETCARE360_CLINICO;
